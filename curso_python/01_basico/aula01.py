"""Aula 01: comentários e docstrings.

Uma docstring documenta módulos, classes ou funções.
Aspas triplas criam strings; não são uma sintaxe especial de comentário.
"""


def main():
    # Comentários começam com # e ajudam a explicar decisões.
    print("A função print exibe uma mensagem na tela.")
    print("Comentários podem ficar acima ou ao lado de uma instrução.")


if __name__ == "__main__":
    main()
