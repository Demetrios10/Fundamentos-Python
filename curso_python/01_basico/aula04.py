"""Exemplo independente de fundamentos de Python."""


def main():
    # Tipos int e float

    print(11) # tipo inteiro positivo
    print(-10) # tipo inteiro negativo
    print(11.2) # tipo float

    print(type(10))
    print(type(-0))
    print(type(10.0))


if __name__ == "__main__":
    main()
