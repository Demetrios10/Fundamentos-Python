"""Aula 10: concatenação (+) e repetição (*) de strings."""


def main():
    concatenacao = "D" + "e" + "m" + "e" + "t" + "r" + "i" + "o" + "s"
    print(concatenacao)

    letra_a_dez_vezes = "A" * 10
    print(letra_a_dez_vezes)

    demetrios_tres_vezes = 3 * "Demetrios"
    print(demetrios_tres_vezes)


if __name__ == "__main__":
    main()
